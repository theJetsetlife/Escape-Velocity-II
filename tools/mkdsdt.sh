#!/bin/bash
# mkdsdt.sh - compile Ps4Pkg/Ps4AcpiDxe/Ps4Dsdt.asl with iasl into the C array Ps4Dsdt.h (checked in, so the
# firmware build does not need iasl). Run after every edit of the .asl.
set -euo pipefail
D=$(cd "$(dirname "$0")/../Ps4Pkg/Ps4AcpiDxe" && pwd)
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
iasl -we -vw 3168 -p "$T/Ps4Dsdt" "$D/Ps4Dsdt.asl" > "$T/iasl.log" 2>&1 || { cat "$T/iasl.log"; exit 1; }
grep -E "Compilation successful|Errors|Warnings" "$T/iasl.log" || true
{
  echo "/* Ps4Dsdt.h - GENERATED by tools/mkdsdt.sh from Ps4Dsdt.asl ($(iasl -v 2>/dev/null | grep -o 'version [0-9]*' | head -1)). Do not edit. */"
  echo "#ifndef PS4_DSDT_H_"; echo "#define PS4_DSDT_H_"
  echo "STATIC CONST UINT8  mPs4DsdtAml[] = {"
  od -An -v -tx1 "$T/Ps4Dsdt.aml" | sed 's/ \([0-9a-f][0-9a-f]\)/ 0x\1,/g; s/^/ /'
  echo "};"; echo "#endif"
} > "$D/Ps4Dsdt.h"
echo "Ps4Dsdt.h: $(stat -c %s "$T/Ps4Dsdt.aml") bytes of AML"
