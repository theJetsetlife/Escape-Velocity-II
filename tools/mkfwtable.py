#!/usr/bin/env python3
"""mkfwtable.py - generate src/directboot/fwtable.h (per-system-software kernel offsets for the stage)

Source: the PS4 Linux loader's offset tables in reference/linux-loader-zip (magic.h: kernel symbols per version,
community-contributed; fw_offsets.h: kmem_alloc and its two patch sites). Only 9.00 is verified against a kernel
dump and on hardware; every other row is marked unverified. phys_avail is not in those tables: it is known for 9.00
only, so the stage recognises other versions but refuses to arm them (src/directboot/arm.c step 0).

The 9.00 row must reproduce the hardware-proven constants below exactly, or generation fails.
    python3 tools/mkfwtable.py            (writes src/directboot/fwtable.h)
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LDR = os.path.join(ROOT, "reference/linux-loader-zip/ps4-linux-loader-master/linux")
OUT = os.path.join(ROOT, "src/directboot/fwtable.h")

# struct field <- magic.h symbol (None = from fw_offsets.h)
FIELDS = [
    ("kmem_alloc", None), ("kmem_patch1", None), ("kmem_patch2", None), ("pstate", None),
    ("kernel_map", "kern_off_kernel_map"), ("kmem_contig", "kern_off_kmem_alloc_contig"),
    ("pmap_extract", "kern_off_pmap_extract"), ("kernel_pmap", "kern_off_kernel_pmap_store"),
    ("icc_nowait", "kern_off_icc_query_nowait"), ("smp_rdv", "kern_off_smp_rendezvous"),
    ("smp_nobarrier", "kern_off_smp_no_rendevous_barrier"), ("wlanbt", "kern_off_wlanbt"),
    ("kern_reboot", "kern_off_kern_reboot"), ("pml4pml4i", "kern_off_pml4pml4i"),
    ("dmpml4i", "kern_off_dmpml4i"), ("dmpdpi", "kern_off_dmpdpi"),
]
# 9.00, hardware-proven (were the K_* constants in db.h); phys_avail and gadget are not in the loader tables
VERIFIED_900 = dict(kmem_alloc=0x37be70, kmem_patch1=0x37bf3c, kmem_patch2=0x37bf44, pstate=0x29a970,
                    kernel_map=0x2268d48, kmem_contig=0x270880, pmap_extract=0x12d050, kernel_pmap=0x1b904b0,
                    icc_nowait=0x2e1760, smp_rdv=0x432bf0, smp_nobarrier=0x432a00, wlanbt=0x180860,
                    kern_reboot=0x29a380, pml4pml4i=0x1b904a0, dmpml4i=0x1b904a4, dmpdpi=0x1b904a8)
EXTRA_900 = dict(phys_avail=0x2216a80, gadget=0x4c7ad)


def parse_magic(path):
    rows, cur, notes = {}, None, {}
    for line in open(path, encoding="utf-8", errors="replace"):
        m = re.match(r"#(?:el)?if(?:def)?\s+(?:defined\s+)?PS4_(\d+)_(\d+)\s*(//.*)?", line)
        if m:
            cur = int(m.group(1)) * 100 + int(m.group(2)); rows[cur] = {}
            notes[cur] = (m.group(3) or "").lstrip("/ ").strip()
            continue
        m = re.match(r"#define\s+(kern_off_\w+)\s+(0x[0-9A-Fa-f]+|\d+)", line)
        if m and cur is not None:
            rows[cur][m.group(1)] = int(m.group(2), 0)
    return rows, notes


def parse_fwoff(path):
    rows = {}
    for m in re.finditer(r"\{\s*(\d+),\s*0x1c0,\s*(0x[0-9A-Fa-f]+),\s*(0x[0-9A-Fa-f]+),\s*(0x[0-9A-Fa-f]+),"
                         r"\s*(0x[0-9A-Fa-f]+),\s*(0x[0-9A-Fa-f]+),\s*(0x[0-9A-Fa-f]+)\s*\}", open(path).read()):
        v = [int(x, 0) for x in m.groups()[1:]]
        rows[int(m.group(1))] = dict(kmem_alloc=v[1], kmem_patch1=v[3], kmem_patch2=v[4], pstate=v[5])
    return rows


def main():
    magic, notes = parse_magic(os.path.join(LDR, "magic.h"))
    fwoff = parse_fwoff(os.path.join(LDR, "fw_offsets.h"))
    vers = sorted(set(magic) & set(fwoff))
    if sorted(magic) != sorted(fwoff):
        print("note: versions only in one table skipped:", sorted(set(magic) ^ set(fwoff)))
    out = []
    for v in vers:
        row = {}
        for f, sym in FIELDS:
            val = fwoff[v][f] if sym is None else magic[v].get(sym)
            if not val:
                sys.exit("missing %s for %d.%02d" % (sym or f, v // 100, v % 100))
            row[f] = val
        if fwoff[v]["pstate"] != magic[v].get("kern_off_pstate_before_shutdown", fwoff[v]["pstate"]):
            sys.exit("pstate differs between magic.h and fw_offsets.h for %d" % v)
        out.append((v, row))
    r900 = dict(out)[900]
    bad = {k: (hex(r900[k]), hex(VERIFIED_900[k])) for k in VERIFIED_900 if r900[k] != VERIFIED_900[k]}
    if bad:
        sys.exit("9.00 row differs from the hardware-proven values: %r" % bad)

    cols = [f for f, _ in FIELDS]
    L = ["/* fwtable.h - GENERATED by tools/mkfwtable.py from reference/linux-loader-zip (magic.h, fw_offsets.h).",
         " * Do not edit. One row per PS4 system software version (offsets from the kernel base).",
         " * DB_FW_VERIFIED: checked against a kernel dump and run on hardware (9.00 only).",
         " * phys_avail = 0: unknown -> the stage recognises the version but refuses to arm it. */",
         "#ifndef DB_FWTABLE_H", "#define DB_FWTABLE_H", "",
         "#include \"fwsel.h\"   /* struct db_kofs (field order below must match) */", "",
         "/* fields: ver, flags, gadget, phys_avail, " + ", ".join(cols) + " */",
         "static const struct db_kofs db_fw_table[] = {"]
    for v, row in out:
        ex = EXTRA_900 if v == 900 else dict(phys_avail=0, gadget=0)
        vals = ", ".join("0x%x" % row[c] for c in cols)
        L.append("    { %4d, %s, 0x%x, 0x%x, %s },   /* %d.%02d %s */" % (
            v, "DB_FW_VERIFIED" if v == 900 else "0", ex["gadget"], ex["phys_avail"], vals,
            v // 100, v % 100, notes.get(v, "")))
    L += ["};", "#define DB_FW_COUNT (sizeof db_fw_table / sizeof db_fw_table[0])", "", "#endif", ""]
    open(OUT, "w").write("\n".join(L))
    print("%s: %d versions (%s)" % (os.path.relpath(OUT, ROOT), len(out),
                                    " ".join("%d.%02d" % (v // 100, v % 100) for v, _ in out)))


if __name__ == "__main__":
    main()
