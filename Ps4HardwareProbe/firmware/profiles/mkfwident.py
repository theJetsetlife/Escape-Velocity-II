#!/usr/bin/env python3
"""mkfwident.py - generate fwident.h (firmware identity profiles) from OpenGoldHEN's per-version kernel
import tables (reference/open-zip/OpenGoldHEN-main/assets/tables/ksdk_offsets_<ver>.bin, 77 u32 in
include/goldhen/kernel.h enum order).

An identity profile confirms WHICH kernel is running, independently of the DMAP offset table: Xfast_syscall
must be at LSTAR, KEXEC_ROP must be the `jmp [rsi]` gadget (the loader contract), the chosen C functions
must start with `push rbp; mov rbp,rsp`, and kernel_map must hold a kernel-half pointer. It carries no DMAP
globals (OpenGoldHEN has none), so on its own it unlocks identification, not memory-dependent diagnostics.

  python3 -I firmware/profiles/mkfwident.py [OPENGOLDHEN_DIR] [KDUMP_900]
With a 9.00 kernel dump every chosen site is checked against it and the script fails on any mismatch.
"""
import os, re, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OGH = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "..", "..", "reference", "open-zip", "OpenGoldHEN-main")
KDUMP = sys.argv[2] if len(sys.argv) > 2 else None
# C functions with a frame prologue (checked on the 9.00 dump); low offsets keep reads inside kernel text
FUNCS = ["IMP_PRINTF", "IMP_MALLOC", "IMP_FREE", "IMP_KMEM_ALLOC", "IMP_KERN_REBOOT", "IMP_VM_MAP_LOOKUP_ENTRY",
         "IMP_KPROC_CREATE", "IMP_SNPRINTF"]
TEXT_BOUND = 0x4a0000          # same bound fwsel's text sites respect on every row

h = open(os.path.join(OGH, "include", "goldhen", "kernel.h")).read()
enum = re.search(r"enum[^{]*\{(.*?)KERNEL_IMPORT_COUNT", h, re.S).group(1)
idx = {n: int(v) for n, v in re.findall(r"(IMP_[A-Z0-9_]+)\s*=\s*(\d+)", enum)}
T = os.path.join(OGH, "assets", "tables")
tabs, origin = {}, {}
EXTRA = os.path.join(HERE, "sources")           # tables extracted from other GoldHEN builds (sources/README.md)
for src in (T, EXTRA):
    for f in sorted(os.listdir(src)) if os.path.isdir(src) else []:
        m = re.match(r"ksdk_offsets_(\d+)\.bin$", f)
        if m and int(m.group(1)) not in tabs:
            d = open(os.path.join(src, f), "rb").read()
            if len(d) != 77 * 4: sys.exit("%s: not 77 u32" % f)
            tabs[int(m.group(1))] = struct.unpack("<77I", d)
            origin[int(m.group(1))] = "OpenGoldHEN" if src == T else "sources/" + f

# cross-check extra tables against the independent offset table (fwtable.h) where both cover a version
ft = open(os.path.join(HERE, "fwtable.h")).read()
FTN = "ver flags gadget phys_avail kmem_alloc kmem_patch1 kmem_patch2 pstate kernel_map".split()
for line in ft.splitlines():
    m = re.match(r"\s+\{\s+(\d+),", line)
    if not m or int(m.group(1)) not in tabs or origin[int(m.group(1))] == "OpenGoldHEN": continue
    row = dict(zip(FTN, [int(x, 0) for x in re.sub(r"[{}\s]", "", line.split("}")[0]).split(",")]))
    t = tabs[row["ver"]]
    for imp, key in (("IMP_KMEM_ALLOC", "kmem_alloc"), ("IMP_KERNEL_MAP", "kernel_map")):
        if t[idx[imp]] != row[key]:
            sys.exit("%s: %s %#x disagrees with fwtable.h %#x" % (origin[row["ver"]], imp, t[idx[imp]], row[key]))
    print("%s: agrees with fwtable.h %d" % (origin[row["ver"]], row["ver"]), file=sys.stderr)

rows, dropped = [], {}
for ver in sorted(tabs):
    t = tabs[ver]
    if t[idx["IMP_XFAST_SYSCALL"]] != 0x1c0:
        sys.exit("ver %d: XFAST_SYSCALL %#x != 0x1c0" % (ver, t[idx["IMP_XFAST_SYSCALL"]]))
    sites = [t[idx[n]] for n in FUNCS if 0 < t[idx[n]] < TEXT_BOUND]
    dropped[ver] = len(FUNCS) - len(sites)
    if len(sites) < 5:
        sys.exit("ver %d: only %d identity sites inside the text bound" % (ver, len(sites)))
    sites = (sites + [0] * 8)[:8]
    rows.append((ver, t[idx["IMP_KEXEC_ROP"]], t[idx["IMP_KERNEL_MAP"]], sites))

if KDUMP:
    k = open(KDUMP, "rb").read()
    r = [x for x in rows if x[0] == 900][0]
    assert k[0x1c0:0x1c8] == bytes.fromhex("0f01f865488924 25".replace(" ", "")), "9.00 dump: Xfast signature"
    assert k[r[1]:r[1] + 2] == b"\xff\x26", "9.00 dump: KEXEC_ROP is not jmp [rsi]"
    for s in r[3]:
        if s: assert k[s:s + 4] == b"\x55\x48\x89\xe5", "9.00 dump: no prologue at %#x" % s
    print("9.00 dump: every identity site matches", file=sys.stderr)

out = ["/* fwident.h - GENERATED by firmware/profiles/mkfwident.py from OpenGoldHEN ksdk_offsets_<ver>.bin",
       " * and firmware/profiles/sources/ (extra: %s)." % (", ".join("%d" % v for v in sorted(origin) if origin[v] != "OpenGoldHEN") or "none"),
       " * Do not edit. Firmware identity profiles: which kernel is running (no DMAP globals). */",
       "#ifndef PRB_FWIDENT_H", "#define PRB_FWIDENT_H", "",
       "struct fw_ident { u16 ver, rsvd; u32 kexec_rop, kernel_map; u32 site[8]; };", "",
       "#define FW_IDENT_COUNT %d" % len(rows),
       "static const struct fw_ident fw_ident_table[FW_IDENT_COUNT] = {"]
for ver, rop, kmap, sites in rows:
    out.append("    { %4d, 0, %#09x, %#09x, { %s } },%s" % (ver, rop, kmap, ", ".join("%#08x" % s for s in sites),
               "   /* %d site(s) beyond the text bound dropped */" % dropped[ver] if dropped[ver] else ""))
out += ["};", "", "#endif", ""]
open(os.path.join(HERE, "fwident.h"), "w").write("\n".join(out))
print("fwident.h: %d versions: %s" % (len(rows), " ".join(str(r[0]) for r in rows)))
